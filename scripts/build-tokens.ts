/**
 * Builds the token outputs from the TypeScript source of truth in src/tokens:
 *
 *   src/styles/tokens.css   CSS custom properties, imported by the app and Storybook
 *   tokens/tokens.json      W3C design-token format, for Figma (Tokens Studio) or other tools
 *
 * Run with `npm run tokens` (Node strips the TypeScript types itself).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  palette,
  semantic,
  fontFamily,
  fontWeight,
  fontSize,
  lineHeight,
  letterSpacing,
  space,
  layout,
  radius,
  shadow,
  motion,
  zIndex,
} from "../src/tokens/index.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const vars: Array<[string, string | number] | string> = [];
const group = (title: string) => vars.push(`\n  /* ${title} */`);

group("Brand palette: three hues, tints and shades");
for (const [hue, scale] of Object.entries(palette)) {
  for (const [step, value] of Object.entries(scale)) vars.push([`--color-${hue}-${step}`, value]);
}

group("Semantic colour roles");
for (const [groupName, roles] of Object.entries(semantic)) {
  if (typeof roles === "string") {
    vars.push([`--${kebab(groupName)}`, roles]);
    continue;
  }
  for (const [role, value] of Object.entries(roles)) vars.push([`--${kebab(groupName)}-${kebab(role)}`, value]);
}

group("Type");
for (const [k, v] of Object.entries(fontFamily)) vars.push([`--font-${k}`, v]);
for (const [k, v] of Object.entries(fontWeight)) vars.push([`--fw-${k}`, v]);
for (const [k, v] of Object.entries(fontSize)) vars.push([`--step-${k}`, v]);
for (const [k, v] of Object.entries(lineHeight)) vars.push([`--lh-${k}`, v]);
for (const [k, v] of Object.entries(letterSpacing)) vars.push([`--ls-${k}`, v]);

group("Space and layout");
for (const [k, v] of Object.entries(space)) vars.push([`--space-${k}`, v]);
for (const [k, v] of Object.entries(layout)) vars.push([`--${k}`, v]);

group("Shape, depth and motion");
for (const [k, v] of Object.entries(radius)) vars.push([`--radius-${k}`, v]);
for (const [k, v] of Object.entries(shadow)) vars.push([`--shadow-${k}`, v]);
for (const [k, v] of Object.entries(motion.duration)) vars.push([`--dur-${k}`, v]);
for (const [k, v] of Object.entries(motion.easing)) vars.push([`--ease-${k}`, v]);
for (const [k, v] of Object.entries(zIndex)) vars.push([`--z-${kebab(k)}`, v]);

const css = `/* Generated by scripts/build-tokens.ts from src/tokens. Do not edit by hand. */
:root {${vars.map((v) => (typeof v === "string" ? v : `\n  ${v[0]}: ${v[1]};`)).join("")}
}
`;

mkdirSync(resolve(root, "src/styles"), { recursive: true });
writeFileSync(resolve(root, "src/styles/tokens.css"), css);

/* W3C design tokens (DTCG) */
type Leaf = { $value: string | number; $type?: string; $description?: string };
const leaf = ($value: string | number, $type?: string): Leaf => ($type ? { $value, $type } : { $value });
const mapValues = <T extends Record<string, string | number>>(o: T, type?: string) =>
  Object.fromEntries(Object.entries(o).map(([k, v]) => [k, leaf(v, type)]));

const json = {
  $description:
    "Solae design tokens. Three brand hues (Lagoon, Coral, Sunshine) with tints and shades, fluid type and space. Generated from src/tokens.",
  color: {
    ...Object.fromEntries(Object.entries(palette).map(([hue, scale]) => [hue, mapValues(scale, "color")])),
    semantic: Object.fromEntries(
      Object.entries(semantic).map(([g, roles]) => [g, typeof roles === "string" ? leaf(roles, "color") : mapValues(roles, "color")]),
    ),
  },
  font: {
    family: mapValues(fontFamily, "fontFamily"),
    weight: mapValues(fontWeight, "fontWeight"),
    size: mapValues(fontSize, "dimension"),
    lineHeight: mapValues(lineHeight, "number"),
    letterSpacing: mapValues(letterSpacing, "dimension"),
  },
  space: mapValues(space, "dimension"),
  layout: mapValues(layout, "dimension"),
  radius: mapValues(radius, "dimension"),
  shadow: mapValues(shadow, "shadow"),
  motion: { duration: mapValues(motion.duration, "duration"), easing: mapValues(motion.easing, "cubicBezier") },
};

mkdirSync(resolve(root, "tokens"), { recursive: true });
writeFileSync(resolve(root, "tokens/tokens.json"), JSON.stringify(json, null, 2) + "\n");

console.log(`tokens: wrote src/styles/tokens.css (${vars.filter((v) => typeof v !== "string").length} variables) and tokens/tokens.json`);
